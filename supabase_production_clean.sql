CREATE TABLE IF NOT EXISTS Usuarios (
    Id integer GENERATED BY DEFAULT AS IDENTITY,
    Email character varying(256) NOT NULL,
    PasswordHash character varying(500) NOT NULL,
    Nombre character varying(100) NOT NULL,
    TiempoDescansoDefectoSegundos integer NOT NULL DEFAULT 90,
    FechaRegistro timestamp with time zone NOT NULL DEFAULT (CURRENT_TIMESTAMP),
    Rol character varying(50) NOT NULL DEFAULT 'User',
    CONSTRAINT PK_Usuarios PRIMARY KEY (Id)
);

CREATE TABLE IF NOT EXISTS Rutinas (
    Id integer GENERATED BY DEFAULT AS IDENTITY,
    UsuarioId integer NOT NULL,
    Nombre character varying(100) NOT NULL,
    DiaSugerido character varying(50),
    Activa boolean NOT NULL DEFAULT TRUE,
    CONSTRAINT PK_Rutinas PRIMARY KEY (Id),
    CONSTRAINT FK_Rutinas_Usuarios_UsuarioId FOREIGN KEY (UsuarioId) REFERENCES Usuarios (Id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS RutinaEjercicios (
    Id integer GENERATED BY DEFAULT AS IDENTITY,
    RutinaId integer NOT NULL,
    EjercicioId integer NOT NULL,
    Orden integer NOT NULL,
    SeriesObjetivo integer NOT NULL,
    DescansoSegundos integer,
    CONSTRAINT PK_RutinaEjercicios PRIMARY KEY (Id),
    CONSTRAINT FK_RutinaEjercicios_Ejercicios_EjercicioId FOREIGN KEY (EjercicioId) REFERENCES Ejercicios (Id) ON DELETE RESTRICT,
    CONSTRAINT FK_RutinaEjercicios_Rutinas_RutinaId FOREIGN KEY (RutinaId) REFERENCES Rutinas (Id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS SesionesEntrenamiento (
    Id integer GENERATED BY DEFAULT AS IDENTITY,
    UsuarioId integer NOT NULL,
    RutinaId integer,
    FechaHoraInicio timestamp with time zone NOT NULL DEFAULT (CURRENT_TIMESTAMP),
    FechaHoraFin timestamp with time zone,
    Notas character varying(1000),
    CONSTRAINT PK_SesionesEntrenamiento PRIMARY KEY (Id),
    CONSTRAINT FK_SesionesEntrenamiento_Rutinas_RutinaId FOREIGN KEY (RutinaId) REFERENCES Rutinas (Id) ON DELETE SET NULL,
    CONSTRAINT FK_SesionesEntrenamiento_Usuarios_UsuarioId FOREIGN KEY (UsuarioId) REFERENCES Usuarios (Id) ON DELETE RESTRICT
);

CREATE TABLE IF NOT EXISTS SeriesRegistro (
    Id integer GENERATED BY DEFAULT AS IDENTITY,
    SesionId integer NOT NULL,
    EjercicioId integer NOT NULL,
    NumeroSerie integer NOT NULL,
    PesoKg numeric(5,2) NOT NULL,
    Repeticiones integer NOT NULL,
    Lado character(1),
    RPE numeric(3,1),
    CONSTRAINT PK_SeriesRegistro PRIMARY KEY (Id),
    CONSTRAINT FK_SeriesRegistro_Ejercicios_EjercicioId FOREIGN KEY (EjercicioId) REFERENCES Ejercicios (Id) ON DELETE RESTRICT,
    CONSTRAINT FK_SeriesRegistro_SesionesEntrenamiento_SesionId FOREIGN KEY (SesionId) REFERENCES SesionesEntrenamiento (Id) ON DELETE CASCADE
);

